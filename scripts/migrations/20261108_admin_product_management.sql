BEGIN;

ALTER TABLE "products"
    ADD COLUMN IF NOT EXISTS "sku" VARCHAR(100),
    ADD COLUMN IF NOT EXISTS "slug" VARCHAR(180),
    ADD COLUMN IF NOT EXISTS "tags" JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS "seo_title" VARCHAR(255),
    ADD COLUMN IF NOT EXISTS "seo_description" VARCHAR(500),
    ADD COLUMN IF NOT EXISTS "is_featured" BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS "display_order" INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "bom_summary" TEXT,
    ADD COLUMN IF NOT EXISTS "content_sections" JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS "reviews_enabled" BOOLEAN NOT NULL DEFAULT TRUE;

CREATE UNIQUE INDEX IF NOT EXISTS "uq_products_sku"
    ON "products" (LOWER("sku")) WHERE "sku" IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "uq_products_slug"
    ON "products" (LOWER("slug")) WHERE "slug" IS NOT NULL;
CREATE INDEX IF NOT EXISTS "ix_products_featured_order"
    ON "products" ("is_featured", "display_order", "product_id");

ALTER TABLE "product_offers"
    ADD COLUMN IF NOT EXISTS "compare_at_price" NUMERIC(15,2),
    ADD COLUMN IF NOT EXISTS "minimum_purchase_quantity" INTEGER NOT NULL DEFAULT 1,
    ADD COLUMN IF NOT EXISTS "maximum_purchase_quantity" INTEGER NOT NULL DEFAULT 100,
    ADD COLUMN IF NOT EXISTS "low_stock_threshold" INTEGER;

ALTER TABLE "product_images"
    ADD COLUMN IF NOT EXISTS "caption" VARCHAR(500),
    ADD COLUMN IF NOT EXISTS "media_type" VARCHAR(16) NOT NULL DEFAULT 'IMAGE',
    ADD COLUMN IF NOT EXISTS "mime_type" VARCHAR(120),
    ADD COLUMN IF NOT EXISTS "file_name" VARCHAR(255);

CREATE TABLE IF NOT EXISTS "product_bom_components" (
    "parent_product_id" NUMERIC(20,0) NOT NULL,
    "component_product_id" NUMERIC(20,0) NOT NULL,
    "quantity" INTEGER NOT NULL DEFAULT 1,
    "component_warranty_months" SMALLINT,
    "display_category" VARCHAR(80) NOT NULL,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    "customer_visible" BOOLEAN NOT NULL DEFAULT TRUE,
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "pk_product_bom_components"
        PRIMARY KEY ("parent_product_id", "component_product_id"),
    CONSTRAINT "fk_product_bom_parent"
        FOREIGN KEY ("parent_product_id") REFERENCES "products" ("product_id") ON DELETE RESTRICT,
    CONSTRAINT "fk_product_bom_component"
        FOREIGN KEY ("component_product_id") REFERENCES "products" ("product_id") ON DELETE RESTRICT,
    CONSTRAINT "chk_product_bom_not_self"
        CHECK ("parent_product_id" <> "component_product_id"),
    CONSTRAINT "chk_product_bom_quantity"
        CHECK ("quantity" > 0),
    CONSTRAINT "chk_product_bom_warranty"
        CHECK ("component_warranty_months" IS NULL OR "component_warranty_months" >= 0)
);
CREATE INDEX IF NOT EXISTS "ix_product_bom_order"
    ON "product_bom_components" ("parent_product_id", "display_order");

CREATE TABLE IF NOT EXISTS "promotion_campaigns" (
    "campaign_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "campaign_code" VARCHAR(100) NOT NULL UNIQUE,
    "campaign_name" VARCHAR(180) NOT NULL,
    "campaign_tag" VARCHAR(80),
    "starts_at" TIMESTAMP,
    "ends_at" TIMESTAMP,
    "priority" INTEGER NOT NULL DEFAULT 100,
    "is_exclusive" BOOLEAN NOT NULL DEFAULT TRUE,
    "is_enabled" BOOLEAN NOT NULL DEFAULT FALSE,
    "created_by" NUMERIC(20,0),
    "updated_by" NUMERIC(20,0),
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_promotion_campaign_created_by"
        FOREIGN KEY ("created_by") REFERENCES "users" ("user_id") ON DELETE SET NULL,
    CONSTRAINT "fk_promotion_campaign_updated_by"
        FOREIGN KEY ("updated_by") REFERENCES "users" ("user_id") ON DELETE SET NULL,
    CONSTRAINT "chk_promotion_campaign_dates"
        CHECK ("starts_at" IS NULL OR "ends_at" IS NULL OR "starts_at" < "ends_at")
);

CREATE TABLE IF NOT EXISTS "product_promotions" (
    "promotion_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "campaign_id" BIGINT NOT NULL,
    "product_id" NUMERIC(20,0) NOT NULL,
    "discount_type" VARCHAR(20) NOT NULL,
    "discount_value" NUMERIC(15,2) NOT NULL,
    "display_copy" VARCHAR(300),
    "sale_badge" VARCHAR(80),
    "eligibility_json" JSONB NOT NULL DEFAULT '{}'::jsonb,
    "starts_at" TIMESTAMP,
    "ends_at" TIMESTAMP,
    "priority" INTEGER NOT NULL DEFAULT 100,
    "is_exclusive" BOOLEAN NOT NULL DEFAULT TRUE,
    "is_enabled" BOOLEAN NOT NULL DEFAULT FALSE,
    "created_by" NUMERIC(20,0),
    "updated_by" NUMERIC(20,0),
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_product_promotions_campaign"
        FOREIGN KEY ("campaign_id") REFERENCES "promotion_campaigns" ("campaign_id") ON DELETE RESTRICT,
    CONSTRAINT "fk_product_promotions_product"
        FOREIGN KEY ("product_id") REFERENCES "products" ("product_id") ON DELETE RESTRICT,
    CONSTRAINT "fk_product_promotions_created_by"
        FOREIGN KEY ("created_by") REFERENCES "users" ("user_id") ON DELETE SET NULL,
    CONSTRAINT "fk_product_promotions_updated_by"
        FOREIGN KEY ("updated_by") REFERENCES "users" ("user_id") ON DELETE SET NULL,
    CONSTRAINT "chk_product_promotion_discount_type"
        CHECK ("discount_type" IN ('PERCENTAGE', 'FIXED_AMOUNT', 'FIXED_PRICE')),
    CONSTRAINT "chk_product_promotion_discount_value"
        CHECK ("discount_value" >= 0 AND
            ("discount_type" <> 'PERCENTAGE' OR "discount_value" <= 100)),
    CONSTRAINT "chk_product_promotion_dates"
        CHECK ("starts_at" IS NULL OR "ends_at" IS NULL OR "starts_at" < "ends_at")
);
CREATE INDEX IF NOT EXISTS "ix_product_promotions_active"
    ON "product_promotions" ("product_id", "is_enabled", "priority", "starts_at", "ends_at");

CREATE TABLE IF NOT EXISTS "promotion_gifts" (
    "promotion_id" BIGINT NOT NULL,
    "gift_offer_id" NUMERIC(20,0) NOT NULL,
    "quantity" INTEGER NOT NULL DEFAULT 1,
    "selection_required" BOOLEAN NOT NULL DEFAULT FALSE,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "pk_promotion_gifts" PRIMARY KEY ("promotion_id", "gift_offer_id"),
    CONSTRAINT "fk_promotion_gifts_promotion"
        FOREIGN KEY ("promotion_id") REFERENCES "product_promotions" ("promotion_id") ON DELETE CASCADE,
    CONSTRAINT "fk_promotion_gifts_offer"
        FOREIGN KEY ("gift_offer_id") REFERENCES "product_offers" ("offer_id") ON DELETE RESTRICT,
    CONSTRAINT "chk_promotion_gift_quantity" CHECK ("quantity" > 0)
);

CREATE TABLE IF NOT EXISTS "product_upgrade_groups" (
    "upgrade_group_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "product_id" NUMERIC(20,0) NOT NULL,
    "group_code" VARCHAR(80) NOT NULL,
    "display_name" VARCHAR(180) NOT NULL,
    "description" VARCHAR(1000),
    "is_required" BOOLEAN NOT NULL DEFAULT FALSE,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    "is_enabled" BOOLEAN NOT NULL DEFAULT FALSE,
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "uq_product_upgrade_group_code" UNIQUE ("product_id", "group_code"),
    CONSTRAINT "fk_product_upgrade_group_product"
        FOREIGN KEY ("product_id") REFERENCES "products" ("product_id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "product_upgrade_options" (
    "upgrade_option_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "upgrade_group_id" BIGINT NOT NULL,
    "offer_id" NUMERIC(20,0) NOT NULL,
    "price_delta" NUMERIC(15,2) NOT NULL DEFAULT 0,
    "display_name" VARCHAR(180),
    "description" VARCHAR(1000),
    "is_default" BOOLEAN NOT NULL DEFAULT FALSE,
    "minimum_quantity" INTEGER NOT NULL DEFAULT 1,
    "maximum_quantity" INTEGER NOT NULL DEFAULT 1,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    "is_enabled" BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT "fk_product_upgrade_option_group"
        FOREIGN KEY ("upgrade_group_id") REFERENCES "product_upgrade_groups" ("upgrade_group_id") ON DELETE CASCADE,
    CONSTRAINT "fk_product_upgrade_option_offer"
        FOREIGN KEY ("offer_id") REFERENCES "product_offers" ("offer_id") ON DELETE RESTRICT,
    CONSTRAINT "uq_product_upgrade_option_offer" UNIQUE ("upgrade_group_id", "offer_id"),
    CONSTRAINT "chk_product_upgrade_quantities"
        CHECK ("minimum_quantity" > 0 AND "maximum_quantity" >= "minimum_quantity"),
    CONSTRAINT "chk_product_upgrade_price_delta" CHECK ("price_delta" >= 0)
);
CREATE INDEX IF NOT EXISTS "ix_product_upgrade_options_order"
    ON "product_upgrade_options" ("upgrade_group_id", "display_order");

CREATE TABLE IF NOT EXISTS "product_bundles" (
    "bundle_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "product_id" NUMERIC(20,0) NOT NULL,
    "bundle_name" VARCHAR(180) NOT NULL,
    "bundle_description" VARCHAR(1000),
    "discount_type" VARCHAR(20) NOT NULL DEFAULT 'FIXED_AMOUNT',
    "discount_value" NUMERIC(15,2) NOT NULL DEFAULT 0,
    "eligibility_json" JSONB NOT NULL DEFAULT '{}'::jsonb,
    "starts_at" TIMESTAMP,
    "ends_at" TIMESTAMP,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    "is_enabled" BOOLEAN NOT NULL DEFAULT FALSE,
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_product_bundle_product"
        FOREIGN KEY ("product_id") REFERENCES "products" ("product_id") ON DELETE RESTRICT,
    CONSTRAINT "chk_product_bundle_discount_type"
        CHECK ("discount_type" IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    CONSTRAINT "chk_product_bundle_discount_value"
        CHECK ("discount_value" >= 0 AND
            ("discount_type" <> 'PERCENTAGE' OR "discount_value" <= 100)),
    CONSTRAINT "chk_product_bundle_dates"
        CHECK ("starts_at" IS NULL OR "ends_at" IS NULL OR "starts_at" < "ends_at")
);

CREATE TABLE IF NOT EXISTS "product_bundle_items" (
    "bundle_id" BIGINT NOT NULL,
    "offer_id" NUMERIC(20,0) NOT NULL,
    "is_required" BOOLEAN NOT NULL DEFAULT FALSE,
    "is_default_selected" BOOLEAN NOT NULL DEFAULT FALSE,
    "display_order" INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT "pk_product_bundle_items" PRIMARY KEY ("bundle_id", "offer_id"),
    CONSTRAINT "fk_product_bundle_item_bundle"
        FOREIGN KEY ("bundle_id") REFERENCES "product_bundles" ("bundle_id") ON DELETE CASCADE,
    CONSTRAINT "fk_product_bundle_item_offer"
        FOREIGN KEY ("offer_id") REFERENCES "product_offers" ("offer_id") ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS "store_display_settings" (
    "setting_key" VARCHAR(100) PRIMARY KEY,
    "setting_value" JSONB NOT NULL,
    "updated_by" NUMERIC(20,0),
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_store_setting_updated_by"
        FOREIGN KEY ("updated_by") REFERENCES "users" ("user_id") ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS "product_review_responses" (
    "review_id" NUMERIC(20,0) PRIMARY KEY,
    "response_text" TEXT NOT NULL,
    "actor_user_id" NUMERIC(20,0),
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_product_review_response_review"
        FOREIGN KEY ("review_id") REFERENCES "product_reviews" ("review_id") ON DELETE CASCADE,
    CONSTRAINT "fk_product_review_response_actor"
        FOREIGN KEY ("actor_user_id") REFERENCES "users" ("user_id") ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS "product_review_moderation_history" (
    "moderation_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "review_id" NUMERIC(20,0) NOT NULL,
    "previous_status" VARCHAR(24),
    "new_status" VARCHAR(24) NOT NULL,
    "note" VARCHAR(1000),
    "actor_user_id" NUMERIC(20,0),
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_product_review_moderation_review"
        FOREIGN KEY ("review_id") REFERENCES "product_reviews" ("review_id") ON DELETE RESTRICT,
    CONSTRAINT "fk_product_review_moderation_actor"
        FOREIGN KEY ("actor_user_id") REFERENCES "users" ("user_id") ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS "admin_product_change_history" (
    "change_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "entity_type" VARCHAR(32) NOT NULL,
    "entity_id" NUMERIC(20,0) NOT NULL,
    "action_code" VARCHAR(40) NOT NULL,
    "changes_json" JSONB NOT NULL DEFAULT '{}'::jsonb,
    "actor_user_id" NUMERIC(20,0),
    "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "fk_admin_product_change_actor"
        FOREIGN KEY ("actor_user_id") REFERENCES "users" ("user_id") ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS "ix_admin_product_change_entity"
    ON "admin_product_change_history" ("entity_type", "entity_id", "created_at" DESC);

ALTER TABLE "products"
    ADD CONSTRAINT "chk_products_tags_array"
        CHECK (jsonb_typeof("tags") = 'array') NOT VALID,
    ADD CONSTRAINT "chk_products_content_sections_array"
        CHECK (jsonb_typeof("content_sections") = 'array') NOT VALID;

ALTER TABLE "product_offers"
    ADD CONSTRAINT "chk_product_offer_compare_at_price"
        CHECK ("compare_at_price" IS NULL OR "compare_at_price" >= "price") NOT VALID,
    ADD CONSTRAINT "chk_product_offer_purchase_quantities"
        CHECK ("minimum_purchase_quantity" > 0
            AND "maximum_purchase_quantity" >= "minimum_purchase_quantity") NOT VALID,
    ADD CONSTRAINT "chk_product_offer_low_stock_threshold"
        CHECK ("low_stock_threshold" IS NULL OR "low_stock_threshold" >= 0) NOT VALID;

ALTER TABLE "product_images"
    ADD CONSTRAINT "chk_product_image_media_type"
        CHECK ("media_type" IN ('IMAGE', 'VIDEO')) NOT VALID;

COMMIT;
