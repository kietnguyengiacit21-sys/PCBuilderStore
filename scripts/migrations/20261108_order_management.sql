BEGIN;

DO $$
BEGIN
    IF to_regclass('"orders"') IS NULL
       OR to_regclass('"order_items"') IS NULL
       OR to_regclass('"users"') IS NULL
       OR to_regclass('"product_offers"') IS NULL THEN
        RAISE EXCEPTION 'Order management migration requires users, product_offers, orders, and order_items.';
    END IF;
END
$$;

ALTER TABLE "orders"
    ADD COLUMN IF NOT EXISTS "idempotency_key" VARCHAR(120);

CREATE UNIQUE INDEX IF NOT EXISTS "uq_orders_idempotency_key"
    ON "orders" ("idempotency_key")
    WHERE "idempotency_key" IS NOT NULL;

ALTER TABLE "order_items"
    ADD COLUMN IF NOT EXISTS "currency_code" CHAR(3);

UPDATE "order_items" oi
SET "currency_code" = po."currency_code"
FROM "product_offers" po
WHERE oi."offer_id" = po."offer_id"
  AND oi."currency_code" IS NULL;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM "order_items" oi
        LEFT JOIN "product_offers" po ON po."offer_id" = oi."offer_id"
        WHERE oi."currency_code" IS NULL
           OR oi."currency_code" COLLATE "C" !~ '^[A-Z]{3}$'
           OR po."currency_code" IS NULL
           OR po."currency_code" COLLATE "C" !~ '^[A-Z]{3}$'
    ) THEN
        RAISE EXCEPTION
            'Existing order items lack a valid currency code from product offers; refusing to set currency_code NOT NULL.';
    END IF;
END
$$;

ALTER TABLE "order_items"
    ALTER COLUMN "currency_code" SET NOT NULL;

CREATE TABLE IF NOT EXISTS "order_status_history" (
    "order_status_history_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_id" NUMERIC(20, 0) NOT NULL REFERENCES "orders" ("order_id") ON DELETE CASCADE,
    "previous_status" VARCHAR(32),
    "new_status" VARCHAR(32),
    "action_code" VARCHAR(40) NOT NULL,
    "actor_user_id" NUMERIC(20, 0) REFERENCES "users" ("user_id") ON DELETE SET NULL,
    "actor_name" VARCHAR(160) NOT NULL,
    "actor_role_code" VARCHAR(40) NOT NULL,
    "note" TEXT,
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS "ix_order_status_history_order_date"
    ON "order_status_history" ("order_id", "created_at", "order_status_history_id");

CREATE TABLE IF NOT EXISTS "order_payment_transactions" (
    "order_payment_transaction_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_id" NUMERIC(20, 0) NOT NULL REFERENCES "orders" ("order_id") ON DELETE RESTRICT,
    "idempotency_key" VARCHAR(120) NOT NULL,
    "provider_code" VARCHAR(40) NOT NULL,
    "payment_method" VARCHAR(40) NOT NULL,
    "outcome_code" VARCHAR(24) NOT NULL,
    "amount" NUMERIC(15, 2) NOT NULL CHECK ("amount" >= 0),
    "currency_code" CHAR(3) NOT NULL,
    "provider_reference" VARCHAR(180) NOT NULL,
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE ("order_id", "idempotency_key"),
    UNIQUE ("provider_reference")
);

CREATE INDEX IF NOT EXISTS "ix_order_payment_transactions_order_date"
    ON "order_payment_transactions" ("order_id", "created_at");

CREATE TABLE IF NOT EXISTS "order_refund_transactions" (
    "order_refund_transaction_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_id" NUMERIC(20, 0) NOT NULL REFERENCES "orders" ("order_id") ON DELETE RESTRICT,
    "idempotency_key" VARCHAR(120) NOT NULL,
    "provider_code" VARCHAR(40) NOT NULL,
    "refund_status" VARCHAR(24) NOT NULL,
    "amount" NUMERIC(15, 2) NOT NULL CHECK ("amount" >= 0),
    "currency_code" CHAR(3) NOT NULL,
    "provider_reference" VARCHAR(180),
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE ("order_id", "idempotency_key"),
    UNIQUE ("provider_reference")
);

CREATE TABLE IF NOT EXISTS "order_inventory_reservations" (
    "order_inventory_reservation_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "order_item_id" NUMERIC(20, 0) NOT NULL UNIQUE REFERENCES "order_items" ("order_item_id") ON DELETE RESTRICT,
    "offer_id" NUMERIC(20, 0) NOT NULL REFERENCES "product_offers" ("offer_id") ON DELETE RESTRICT,
    "quantity" INTEGER NOT NULL CHECK ("quantity" > 0),
    "reservation_status" VARCHAR(16) NOT NULL CHECK (
        "reservation_status" IN ('ACTIVE', 'RELEASED', 'CONSUMED')
    ),
    "created_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS "ix_order_inventory_reservations_offer_status"
    ON "order_inventory_reservations" ("offer_id", "reservation_status");

COMMIT;
