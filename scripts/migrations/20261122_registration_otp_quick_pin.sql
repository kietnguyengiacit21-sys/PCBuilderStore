-- Usernames, email-verified sign-up (6-digit code) and the customer quick-login PIN.
-- Safe to run more than once.

-- Optional login name, stored lowercase by the application. Older accounts have none until the
-- owner sets one on the account page, so it is only unique when present.
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "username" VARCHAR(30);
CREATE UNIQUE INDEX IF NOT EXISTS "uq_users_username" ON "users" ("username") WHERE "username" IS NOT NULL;

-- Set when the customer proved they own the email with a sign-up code.
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "email_verified_at" TIMESTAMP WITHOUT TIME ZONE;

-- BCrypt hash of the customer's 8-digit quick-login PIN; NULL means quick login is off.
-- Cleared whenever the password changes or the account stops being a customer account.
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "quick_pin_hash" VARCHAR(100);
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "quick_pin_updated_at" TIMESTAMP WITHOUT TIME ZONE;

CREATE TABLE IF NOT EXISTS "email_verification_codes" (
    "code_id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "email" VARCHAR(254) NOT NULL,
    "purpose" VARCHAR(20) NOT NULL DEFAULT 'REGISTER' CHECK ("purpose" IN ('REGISTER')),
    -- SHA-256 of "email:code"; the code itself is never stored.
    "code_hash" CHAR(64) NOT NULL,
    "attempts" INTEGER NOT NULL DEFAULT 0,
    "expires_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    "used_at" TIMESTAMP WITHOUT TIME ZONE,
    "created_at" TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS "ix_email_verification_codes_email"
    ON "email_verification_codes" ("email", "purpose", "created_at" DESC);

-- Quick-login PIN changes show up in the account history next to the admin actions.
ALTER TABLE "user_account_events" DROP CONSTRAINT IF EXISTS "user_account_events_event_type_check";
ALTER TABLE "user_account_events" ADD CONSTRAINT "user_account_events_event_type_check"
    CHECK ("event_type" IN ('CREATED', 'LOCKED', 'UNLOCKED', 'PASSWORD_RESET_BY_ADMIN', 'PASSWORD_RESET_BY_EMAIL',
                            'QUICK_PIN_SET', 'QUICK_PIN_REMOVED'));
